package com.prostovoice.audio

import com.prostovoice.domain.AsrSegment

/** A bounded window of 16 kHz mono samples for native inference. */
data class InferenceAudioChunk(
    val startSample: Long,
    val samples: FloatArray,
) {
    val endSample: Long get() = startSample + samples.size
}

object AudioChunker {
    const val DEFAULT_CHUNK_DURATION_MS = 30_000L
    const val DEFAULT_OVERLAP_MS = 2_000L

    fun split(
        samples: FloatArray,
        sampleRate: Int = 16_000,
        chunkDurationMs: Long = DEFAULT_CHUNK_DURATION_MS,
        overlapMs: Long = DEFAULT_OVERLAP_MS,
    ): List<InferenceAudioChunk> {
        require(sampleRate > 0) { "sampleRate must be positive" }
        require(chunkDurationMs > 0) { "chunkDurationMs must be positive" }
        require(overlapMs >= 0 && overlapMs < chunkDurationMs) {
            "overlapMs must be in [0, chunkDurationMs)"
        }
        if (samples.isEmpty()) return emptyList()
        val window = (chunkDurationMs * sampleRate / 1_000L).toInt().coerceAtLeast(1)
        val overlap = (overlapMs * sampleRate / 1_000L).toInt().coerceAtLeast(0)
        val step = window - overlap
        val result = mutableListOf<InferenceAudioChunk>()
        var start = 0
        while (start < samples.size) {
            val end = minOf(start + window, samples.size)
            result += InferenceAudioChunk(start.toLong(), samples.copyOfRange(start, end))
            if (end == samples.size) break
            start += step
        }
        return result
    }

    /** Removes repeated ASR windows generated by overlap between adjacent chunks. */
    fun deduplicateAsrSegments(segments: List<AsrSegment>): List<AsrSegment> {
        val result = mutableListOf<AsrSegment>()
        for (segment in segments.sortedWith(compareBy<AsrSegment> { it.startMs }.thenBy { it.endMs })) {
            if (segment.text.isBlank() || segment.endMs <= segment.startMs) continue
            val normalized = normalize(segment.text)
            val duplicate = result.asReversed().takeWhile { segment.startMs - it.endMs <= 4_000L }
                .any { previous ->
                    normalize(previous.text) == normalized &&
                        segment.startMs < previous.endMs && segment.endMs > previous.startMs
                }
            if (!duplicate) result += segment
        }
        return result
    }

    private fun normalize(text: String): String = text.trim().lowercase().replace(Regex("\\s+"), " ")
}
